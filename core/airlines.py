# 反查表：全称→码 / 简称→码（模块级构建一次）
_FULL2CODE = {full: c for c, (full, _s) in _AIRLINES.items()}
_SHORT2CODE = {s: c for c, (_f, s) in _AIRLINES.items() if s}

# 常用形增补：渠道航司字段的实际显示形/用户惯写形（官方全称带
